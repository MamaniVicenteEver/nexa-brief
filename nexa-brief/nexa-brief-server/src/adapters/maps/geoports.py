from pathlib import Path
from typing import Any, Protocol


class GeoDataPort(Protocol):
    def build(self, country: str | None = None, level: int | None = None, tolerance: float = 0.005) -> dict[str, int]: ...
    def resolve(self, query: str | dict[str, Any]) -> dict[str, Any]: ...
    def resolve_scene(self, scene_path: str | Path) -> Path: ...
    def list_regions(self, level: int, country: str | None = None) -> list[dict[str, Any]]: ...
