async def main():
    print("=" * 70)
    print("🔬 NEXA BRIEF — SUITE DE VERIFICACIÓN DE PUBLICACIÓN")
    print("=" * 70)

    # 1. Verificar clave de cifrado
    encryption_key = settings.publisher_encryption_key
    if not encryption_key:
        print("❌ Falta PUBLISHER_ENCRYPTION_KEY en el .env")
        sys.exit(1)

    # 2. Cargar token storage
    accounts_path = settings.accounts_json_path
    if not accounts_path.exists():
        print(f"❌ No existe accounts.json en: {accounts_path}")
        sys.exit(1)

    storage = TokenStorage(path=accounts_path, encryption_key=encryption_key)
    facade = get_publisher_facade()

    # 3. Detectar qué plataformas están configuradas
    platforms = list(storage._data.keys())
    print(f"✅ Plataformas configuradas en accounts.json: {platforms}")
    
    # Listar cuentas con su alias
    accounts = storage.list_accounts()
    for acc in accounts:
        print(f"   • {acc['platform']}:{acc['alias']} → Nombre: '{acc['name']}' | Status: {acc['status']}")

    print("\n¿Qué plataforma deseas probar?")
    print("  [1] YouTube (canal_1)")
    print("  [2] Facebook (pagina_1)")
    print("  [3] TikTok (cuenta_1)")
    # If both youtube and facebook are present, suggest options. Let's suggest testing all configured.
    print("  [4] Probar todas las configuradas (Secuencial)")
    
    choice = input("Elige una opción (1-4) [4]: ").strip() or "4"

    if choice == "1":
        await test_youtube(facade, storage)
    elif choice == "2":
        await test_facebook(facade, storage)
    elif choice == "3":
        await test_tiktok(facade, storage)
    else:
        # Run what is configured in storage
        configured_platforms = [acc['platform'] for acc in accounts]
        if "youtube" in configured_platforms:
            await test_youtube(facade, storage)
        if "facebook" in configured_platforms:
            await test_facebook(facade, storage)
        if "tiktok" in configured_platforms:
            await test_tiktok(facade, storage)


if __name__ == "__main__":
    asyncio.run(main())