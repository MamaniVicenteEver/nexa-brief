def find_recent_video(platform: str) -> Path:
    """Search for the most recent video generated in the output directory."""
    output_dir = settings.output_dir
    filename = "tiktok_video.mp4" if platform == "tiktok" else "youtube_video.mp4"
    
    videos = sorted(
        output_dir.rglob(filename),
        key=lambda p: p.stat().st_mtime,
        reverse=True
    )
    
    # Fallback to any MP4 in output/ if platform-specific video isn't found
    if not videos:
        videos = sorted(
            output_dir.rglob("*.mp4"),
            key=lambda p: p.stat().st_mtime,
            reverse=True
        )
        
    if not videos:
        print(f"\n❌ Error: No se encontró ningún video (.mp4) en: {output_dir.absolute()}")
        print("   Por favor genera un video primero usando el pipeline de Nexa Brief.")
        sys.exit(1)
        
    return videos[0]


async def test_youtube(facade, storage):
    print("\n" + "=" * 50)
    print("🚀 PUBLICANDO EN YOUTUBE (canal_1)...")
    print("=" * 50)
    
    video = find_recent_video("youtube")
    print(f"🎬 Video seleccionado: {video.name} ({round(video.stat().st_size / 1_048_576, 2)} MB)")
    
    playlist_id = None
    try:
        yt_adapter = facade._adapters["youtube"]
        print("\n¿Deseas agregar este video a una lista de reproducción (Playlist)?")
        print("  [s] Sí, seleccionar o crear una Playlist")
        print("  [n] No, publicar directamente")
        playlist_choice = input("Elige una opción (s/n) [n]: ").strip().lower() or "n"
        
        if playlist_choice == "s":
            print("\n⏳ Obteniendo listas de reproducción del canal...")
            playlists = await yt_adapter.list_playlists("canal_1")
            
            print("\nListas de reproducción disponibles:")
            print("  [0] Crear una nueva Playlist")
            for idx, pl in enumerate(playlists, start=1):
                print(f"  [{idx}] {pl['title']} (ID: {pl['id']})")
            
            selection = input(f"Elige una opción (0-{len(playlists)}): ").strip()
            if not selection.isdigit():
                print("Selección no válida. Se publicará sin asociar a playlist.")
            else:
                sel_idx = int(selection)
                if sel_idx == 0:
                    print("\n📝 Creando nueva Playlist:")
                    pl_title = input("  Título de la playlist: ").strip()
                    pl_desc = input("  Descripción de la playlist: ").strip()
                    if pl_title:
                        print("⏳ Creando playlist en YouTube...")
                        playlist_id = await yt_adapter.create_playlist(pl_title, pl_desc, "canal_1")
                        print(f"✅ Playlist creada con ID: {playlist_id}")
                    else:
                        print("❌ El título no puede estar vacío. Se publicará sin playlist.")
                elif 1 <= sel_idx <= len(playlists):
                    playlist_id = playlists[sel_idx - 1]["id"]
                    print(f"✅ Seleccionado: '{playlists[sel_idx - 1]['title']}'")
                else:
                    print("Selección fuera de rango. Se publicará sin playlist.")
        print("\n¿Deseas publicar este video como un YouTube Short? (Formato vertical, < 60 seg)")
        print("  [s] Sí, agregar #Shorts al título")
        print("  [n] No, publicar como video estándar")
        short_choice = input("Elige una opción (s/n) [n]: ").strip().lower() or "n"
    except Exception as e:
        print(f"⚠️ Error al interactuar con playlists: {e}")
        print("Continuando con la subida del video sin playlist...")
        short_choice = "n"

    try:
        title = "Focus & Code Beats — Nexa Brief"
        if short_choice == "s":
            title = "Focus & Code Beats — Nexa Brief #Shorts"

        result = await facade.publish_video(
            video_path=video,
            title=title,
            description=(
                "🎵 Ambient lofi music generated by Drova Soft's Nexa Brief AI pipeline.\n"
                "Perfect for deep work, studying, or relaxing."
            ),
            tags=["lofi", "coding", "productivity", "study"],
            account_selector="youtube:canal_1",
        )
        print("\n" + "=" * 60)
        print("🎉 ¡ÉXITO! VIDEO PUBLICADO EN YOUTUBE")
        print("=" * 60)
        print(f"   Video ID : {result.post_id}")
        print(f"   URL      : {result.url}")
        
        if playlist_id:
            try:
                print(f"⏳ Agregando video {result.post_id} a la playlist {playlist_id}...")
                await yt_adapter.add_video_to_playlist(result.post_id, playlist_id, "canal_1")
                print("✅ Video agregado con éxito a la playlist.")
            except Exception as e:
                print(f"❌ Error al agregar video a la playlist: {e}")
                
        print("=" * 60)
    except Exception as e:
        print(f"\n❌ Falló YouTube: {e}")


